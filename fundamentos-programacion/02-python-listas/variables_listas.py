#Crear una lista de elementos
lista1 = ["a", "c", "d", "a", "l", "m"]
print(lista1)

#Contar cuantas veces se repite un elemento
repeticiones = lista1.count("a")
print(repeticiones)

#Eliminar un elemento de la lista
lista1.remove("d")
print(lista1)

#Insertar un elemento en la lista
lista1.insert(2, "p")
print(lista1)

#Ordenar la lista
lista1.sort()
print(lista1)